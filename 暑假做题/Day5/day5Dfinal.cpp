#include <bits/stdc++.h>
using namespace std;

#define ll long long

// ================================================================
// 快速输入模板（比 cin 快，适合竞赛）
// ================================================================
// 依据：q≤100，n≤1e6，使用快速读入可提升效率
template<class I>
inline void read(I &num){
    num = 0;
    char c = getchar();
    char up = c;
    while(!isdigit(c)) {
        up = c;
        c = getchar();
    }
    while(isdigit(c)) {
        num = (num << 1) + (num << 3) + (c ^ '0');
        c = getchar();
    }
    if(up == '-') num = -num;
}

// ================================================================
// 欧拉线性筛：生成 <= limit 的所有质数
// ================================================================
// 依据：每个合数只会被其最小质因子标记一次，时间复杂度 O(n)
// 内存：limit=1415，质数约223个，占用 < 1KB
vector<int> sievePrimes(int limit){
    vector<int> primes;
    vector<char> isComp(limit + 1, 0);  // isComp[i]=1 表示 i 是合数

    for(int i = 2; i <= limit; i++){
        // 如果 i 未被标记为合数，则 i 是质数
        if(!isComp[i]) {
            primes.push_back(i);
        }

        // 用当前质数表标记合数
        for(int p : primes){
            // 1LL 防止 int 乘法溢出（虽然 limit 很小，但这是良好习惯）
            if(1LL * i * p > limit) break;

            isComp[i * p] = 1;  // 标记 i*p 为合数

            // 关键：如果 i 能被 p 整除，停止继续标记
            // 依据：保证每个合数只被其最小质因子标记一次
            if(i % p == 0) break;
        }
    }
    return primes;
}

// ================================================================
// 求 n 的最小质因子（Smallest Prime Factor）
// ================================================================
// 依据：如果 n 是合数，必有一个质因子 <= sqrt(n)
// 时间复杂度：O(π(√n))，最多约 223 次循环
int spf(int n, const vector<int>& primes){
    for(int p : primes){
        // 如果 p*p > n，后面的质数更大，不可能整除 n
        if(1LL * p * p > n) break;

        if(n % p == 0) {
            return p;  // 找到最小质因子
        }
    }
    return n;  // 没有找到因子，说明 n 本身是质数
}

// ================================================================
// 求 k 的正因子个数（约数个数）
// ================================================================
// 依据：若 k = p1^e1 * p2^e2 * ... * pm^em
//       则因子个数 = (e1+1) * (e2+1) * ... * (em+1)
// 时间复杂度：O(π(√k))，k ≤ 2e6，√k ≈ 1414
int divisors(int k, const vector<int>& primes){
    int cnt = 1;  // 累乘器，初始为 1

    for(int p : primes){
        // 如果 p*p > k，说明 k 已经没有大于等于 p 的质因子
        if(1LL * p * p > k) break;

        if(k % p == 0){
            int e = 0;
            // 连续除以 p，统计指数 e
            while(k % p == 0){
                k /= p;
                e++;
            }
            // 根据公式乘上 (e+1)
            cnt *= (e + 1);
        }
    }

    // 如果循环结束后 k > 1，说明 k 本身是一个质数（指数为 1）
    // 依据：质因数分解后剩余的大质数，指数为 1，贡献因子 (1+1)=2
    if(k > 1) {
        cnt *= 2;
    }

    return cnt;
}

// ================================================================
// 主函数
// ================================================================
int main(){
    // ------------------------------------------------------------
    // 第1步：生成质数表
    // ------------------------------------------------------------
    // 依据：计算 divisors(n+p) 时，n ≤ 1e6，p ≤ n（最小质因子 ≤ n）
    //       所以 n+p ≤ 2e6，√(2e6) ≈ 1414.2，取 1415 足够
    vector<int> primes = sievePrimes(1415);

    // ------------------------------------------------------------
    // 第2步：预处理所有可能的余数组合
    // ------------------------------------------------------------
    // 依据：条件 (2x?+3x+5n) % 77 == 0 只取决于 x%77 和 n%77
    //       因为模运算满足：(a+b)%m = (a%m + b%m)%m
    //       所以预计算 77×77=5929 种组合，后续 O(1) 查询
    vector<int> valid[77];  // valid[m] 存储所有满足条件的 x%77 的余数 r

    for(int m = 0; m < 77; m++){          // m = n % 77
        for(int r = 0; r < 77; r++){      // r = x % 77
            // 检查该余数组合是否满足整除条件
            if((2 * r * r + 3 * r + 5 * m) % 77 == 0){
                valid[m].push_back(r);
            }
        }
    }

    // ------------------------------------------------------------
    // 第3步：读入所有询问（离线处理）
    // ------------------------------------------------------------
    // 依据：由于所有询问的 n 已知，可以排序后一次性扫描
    //       避免对每个询问重复遍历 x
    int q;
    read(q);

    // pair< n值, 原始输入下标 >
    // 原始下标用于保证输出顺序与输入一致
    vector<pair<int, int>> queries(q);
    int maxN = 0;  // 所有询问中最大的 n，决定循环上限

    for(int i = 0; i < q; i++){
        read(queries[i].first);   // 读取 n
        queries[i].second = i;    // 记录原始下标
        maxN = max(maxN, queries[i].first);
    }

    // 按 n 从小到大排序
    // 依据：这样在扫描 n 从 1 到 maxN 时，可以依次回答询问
    sort(queries.begin(), queries.end());

    // ------------------------------------------------------------
    // 第4步：初始化输出数组和余数贡献数组
    // ------------------------------------------------------------
    vector<ll> answer(q);  // answer[原始下标] = 该询问的答案

    // sumResidue[r]：所有满足 x%77==r 且 x ≤ 当前 n 的 x 的贡献之和
    // 依据：贡献 = divisors(x + spf(x))，即 z 的个数
    ll sumResidue[77] = {0};

    int ptr = 0;  // 指向 queries 中下一个待回答的询问

    // ------------------------------------------------------------
    // 第5步：核心循环 - 增量计算
    // ------------------------------------------------------------
    // 依据：每个 x 只处理一次，所有询问共享计算结果
    //       时间复杂度 O(maxN × (质数表遍历))，而非 O(q × maxN)
    for(int n = 1; n <= maxN; n++){
        // --------------------------------------------------------
        // 5.1 加入 x = n 的贡献
        // --------------------------------------------------------
        // 依据：x=1 没有"除1以外的最小正因子"，所以跳过
        if(n >= 2){
            // p = x 的最小质因子，对应题目中的 y
            int p = spf(n, primes);

            // contribution = divisors(x + y) = z 的个数
            int contribution = divisors(n + p, primes);

            // 按 x%77 分类累加
            // 依据：后续回答询问时，只需要知道 x%77 的余数
            sumResidue[n % 77] += contribution;
        }

        // --------------------------------------------------------
        // 5.2 回答所有 n 等于当前值的询问
        // --------------------------------------------------------
        // 依据：可能有多个询问的 n 相同，一次性全部回答
        while(ptr < q && queries[ptr].first == n){
            ll ans = 0;

            // 对于当前 n，所有满足条件的 x 的余数都在 valid[n%77] 中
            // 依据：预处理阶段已经验证了这些余数组合
            for(int r : valid[n % 77]){
                ans += sumResidue[r];
            }

            // 按原始下标存储答案
            answer[queries[ptr].second] = ans;
            ptr++;
        }
    }

    // ------------------------------------------------------------
    // 第6步：按原始输入顺序输出答案
    // ------------------------------------------------------------
    for(int i = 0; i < q; i++){
        cout << answer[i] << '\n';
    }

    return 0;
}