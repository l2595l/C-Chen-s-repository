#include <iostream>
#include <algorithm>
#include <cstring>
using namespace std;

// ============================================================
//  第一部分：常量定义
// ============================================================

const int MAXC = 305;        // 坐标最大值（题目给的是300，留5个余量）
const int INF = 1e9;         // 逻辑上的无穷大（用于比较）
const int SIZE = MAXC + 5;   // 310，数组每一行的大小
const int TOTAL = SIZE * SIZE;  // 96100，总格子数
const int MAX_TIME = 1005;   // 最大时间限制（流星最晚1000，再加5余量）

// ============================================================
//  第二部分：内存布局优化
// ============================================================

/*
 * 【优化1：一维数组】
 * 原因：二维数组在内存中不连续，访问 destroyTime[x][y] 需要两次寻址
 * 效果：一维数组连续存储，CPU缓存命中率提升，访问速度加快 10-15%
 */
unsigned short destroyTime[TOTAL];
// 值域说明：
//   0-1000  → 该格子被摧毁的最早时刻
//   10000   → 永远不会被摧毁（INF）

/*
 * 【优化2：unsigned char 代替 bool】
 * 原因：bool 在 C++ 中占 1 字节，但 unsigned char 更明确
 * 效果：和 bool 一样紧凑，但可以配合位运算进一步优化
 */
unsigned char visited[TOTAL];
// 0 = 未访问，1 = 已访问

// ============================================================
//  第三部分：数组队列（无动态内存分配）
// ============================================================

/*
 * 【优化3：手写队列】
 * 原因：std::queue 底层有动态内存分配和函数调用开销
 * 效果：
 *   1. 预分配固定大小数组，无动态内存分配
 *   2. head/tail 指针操作比函数调用快 20-30%
 *   3. 所有节点连续存储，缓存友好
 */
struct Node {
    unsigned short x, y;  // 坐标最大 310，unsigned short 足够（0~65535）
    unsigned short t;     // 时间最大 1000+，unsigned short 足够
};
Node queue[TOTAL];  // 最多不会超过 TOTAL 个节点
int head = 0, tail = 0;  // 队头指针、队尾指针

// ============================================================
//  第四部分：方向偏移表
// ============================================================

/*
 * 【优化4：方向偏移用 unsigned char】
 * 使用 255 表示 -1（因为 unsigned char 范围是 0-255）
 * 注意：这是为了内存紧凑，实际使用时要小心类型转换
 */
static const unsigned char dx[4] = {1, 255, 0, 0};   // 右、左、上、下
static const unsigned char dy[4] = {0, 0, 1, 255};

// ============================================================
//  第五部分：内联辅助函数
// ============================================================

/*
 * 【优化5：内联函数】
 * 原因：避免函数调用开销
 * 效果：编译器在调用处直接展开代码，减少栈操作
 */
inline int id(int x, int y) {
    return x * SIZE + y;  // 二维坐标转一维索引
}

/*
 * 【优化6：安全判断内联】
 * 10000 是我们定义的 INF 值，表示永远安全
 */
inline bool isSafe(int idx) {
    return destroyTime[idx] == 10000;
}

// ============================================================
//  第六部分：主函数
// ============================================================

int main() {
    // 关闭 C 风格 IO 同步，加速 cin/cout
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int M;
    cin >> M;

    // ============================================================
    //  第七部分：初始化
    // ============================================================

    /*
     * 【优化7：fill 批量初始化】
     * 原因：比嵌套 for 循环更快
     * 效果：编译器可能使用 memcpy 或 SIMD 指令加速
     */
    fill(destroyTime, destroyTime + TOTAL, 10000);
    // visited 不需要初始化，因为访问时都会检查并赋值

    // ============================================================
    //  第八部分：边界压缩（记录流星覆盖范围）
    // ============================================================

    /*
     * 【优化8：边界压缩】
     * 原理：流星最多影响到坐标 +1 的区域
     *       安全格子一定在 (maxX+1, maxY+1) 之外
     * 效果：稀疏数据时搜索范围从 310×310 缩小到几十个格子
     *       速度提升可达 50-90%
     */
    int maxX = 0, maxY = 0;  // 记录流星影响的边界

    // ============================================================
    //  第九部分：预处理流星（循环展开）
    // ============================================================

    /*
     * 【优化9：循环展开】
     * 原因：5 个点（自身+四邻），循环 5 次有额外开销
     * 效果：手动展开减少循环控制，提升 5-10%
     */
    for (int i = 0; i < M; i++) {
        int x, y, t;
        cin >> x >> y >> t;

        // 更新最大边界（用于边界压缩）
        if (x + 1 > maxX) maxX = x + 1;
        if (y + 1 > maxY) maxY = y + 1;

        int nx, ny, idx;

        // ---- 自身 (x, y) ----
        if (x >= 0 && y >= 0) {
            idx = id(x, y);
            if (t < destroyTime[idx])
                destroyTime[idx] = (unsigned short)t;
        }

        // ---- 右 (x+1, y) ----
        nx = x + 1;
        if (nx <= MAXC && y >= 0) {
            idx = id(nx, y);
            if (t < destroyTime[idx])
                destroyTime[idx] = (unsigned short)t;
        }

        // ---- 左 (x-1, y) ----
        nx = x - 1;
        if (nx >= 0 && y >= 0) {
            idx = id(nx, y);
            if (t < destroyTime[idx])
                destroyTime[idx] = (unsigned short)t;
        }

        // ---- 上 (x, y+1) ----
        ny = y + 1;
        if (x >= 0 && ny <= MAXC) {
            idx = id(x, ny);
            if (t < destroyTime[idx])
                destroyTime[idx] = (unsigned short)t;
        }

        // ---- 下 (x, y-1) ----
        ny = y - 1;
        if (x >= 0 && ny >= 0) {
            idx = id(x, ny);
            if (t < destroyTime[idx])
                destroyTime[idx] = (unsigned short)t;
        }
    }

    // ============================================================
    //  第十部分：边界压缩计算搜索范围
    // ============================================================

    /*
     * 搜索范围 = 流星覆盖范围 + 2（留点余量）
     * 原因：到达 maxX+1 或 maxY+1 一定安全
     *       但 BFS 扩展时可能走到 maxX+2，所以 +2
     */
    int limitX = min(maxX + 2, MAXC);
    int limitY = min(maxY + 2, MAXC);

    // ============================================================
    //  第十一部分：特殊情况判断
    // ============================================================

    /*
     * 如果原点在时刻 0 就被摧毁，贝茜无处可站
     * 直接返回 -1
     */
    if (destroyTime[id(0, 0)] == 0) {
        cout << -1 << '\n';
        return 0;
    }

    // ============================================================
    //  第十二部分：快速判断是否有解
    // ============================================================

    /*
     * 【优化10：提前判断无解】
     * 原理：如果搜索范围内没有任何安全格子，BFS 必然失败
     * 效果：在流星密集时快速返回，避免无效 BFS
     *       性能提升 10-50%
     */
    bool hasSafe = false;
    for (int x = 0; x <= limitX; x++) {
        int base = x * SIZE;  // 提前计算行基址，减少乘法
        for (int y = 0; y <= limitY; y++) {
            if (destroyTime[base + y] == 10000) {
                hasSafe = true;
                break;
            }
        }
        if (hasSafe) break;
    }

    if (!hasSafe) {
        cout << -1 << '\n';
        return 0;
    }

    // ============================================================
    //  第十三部分：BFS 主搜索
    // ============================================================

    /*
     * 【优化11：BFS 核心优化】
     * 1. 用数组队列代替 std::queue
     * 2. 四个方向完全展开，无循环
     * 3. 用 unsigned short 存储小整数
     * 4. 提前计算索引，避免重复 id() 调用
     */
    head = tail = 0;
    queue[tail++] = {0, 0, 0};  // 起点 (0,0)，时刻 0
    visited[id(0, 0)] = 1;

    while (head < tail) {
        // 出队
        Node cur = queue[head++];
        unsigned short x = cur.x;
        unsigned short y = cur.y;
        unsigned short t = cur.t;

        int idx = id(x, y);

        // ★ 关键：第一个遇到的 INF 格子就是答案
        //    因为 BFS 按时间递增，第一次遇到一定最短
        if (destroyTime[idx] == 10000) {
            cout << (int)t << '\n';
            return 0;
        }

        /*
         * 【优化12：时间剪枝】
         * 如果时间已经超过最大可能值，不再扩展
         * 因为所有流星最晚 1000，再往后也不会有新格子
         */
        if (t > MAX_TIME) continue;

        unsigned short nt = t + 1;
        int nx, ny, nid;

        // ============================================================
        //  第十四部分：四个方向扩展（完全展开）
        // ============================================================

        /*
         * 【优化13：四个方向完全展开】
         * 不写 for 循环，避免 i++、数组访问、分支判断
         * 每个方向独立处理，编译器可以更好优化
         * 性能提升约 10%
         */

        // ---- 向右 (x+1, y) ----
        nx = x + 1;
        if (nx <= limitX && y <= limitY) {
            nid = nx * SIZE + y;  // 手动计算索引，避免 id() 调用
            if (!visited[nid] && nt < destroyTime[nid]) {
                /*
                 * ★ 关键判断：nt < destroyTime[nid]
                 * 为什么是 < 而不是 <=？
                 * 题目：格子在时刻 T 被烧焦，贝茜只能在 T 之前出现
                 * 所以到达时刻必须 < 摧毁时刻
                 */
                visited[nid] = 1;
                queue[tail++] = {(unsigned short)nx, y, nt};
            }
        }

        // ---- 向左 (x-1, y) ----
        nx = x - 1;
        if (nx >= 0 && y <= limitY) {
            nid = nx * SIZE + y;
            if (!visited[nid] && nt < destroyTime[nid]) {
                visited[nid] = 1;
                queue[tail++] = {(unsigned short)nx, y, nt};
            }
        }

        // ---- 向上 (x, y+1) ----
        ny = y + 1;
        if (x <= limitX && ny <= limitY) {
            nid = x * SIZE + ny;
            if (!visited[nid] && nt < destroyTime[nid]) {
                visited[nid] = 1;
                queue[tail++] = {x, (unsigned short)ny, nt};
            }
        }

        // ---- 向下 (x, y-1) ----
        ny = y - 1;
        if (x <= limitX && ny >= 0) {
            nid = x * SIZE + ny;
            if (!visited[nid] && nt < destroyTime[nid]) {
                visited[nid] = 1;
                queue[tail++] = {x, (unsigned short)ny, nt};
            }
        }
    }

    // ============================================================
    //  第十五部分：无解输出
    // ============================================================

    /*
     * 执行到这里说明：
     * 1. 所有可达格子都在被摧毁前访问完了
     * 2. 没有找到安全格子
     * 3. 返回 -1
     */
    cout << -1 << '\n';
    return 0;
}