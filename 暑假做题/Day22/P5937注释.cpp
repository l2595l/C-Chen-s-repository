#include<bits/stdc++.h>
using namespace std;

// 定义结构体存储每一组询问
struct hzy{
	int x, y, z; // x表示左端点l-1（转化后的），y表示右端点r，z表示奇偶性（0为even，1为odd）
}a[200001];

int f[200001];   // 并查集数组，大小开2倍，因为要扩展域（偶数域+奇数域）
int n, m, b[200001], l; // n是原序列长度，m是询问次数，b数组用于离散化，l记录离散化后的点数

// 并查集查找函数（带路径压缩）
int zuxian(int k){
	// 如果自己是老大就返回自己，否则递归找老大，并把沿途节点的老大都直接设为终极老大（路径压缩）
	return f[k]==k ? k : f[k]=zuxian(f[k]);
}

// 并查集合并函数
void hebing(int x, int y){
	int x1 = zuxian(x); // 找x的老大
	int x2 = zuxian(y); // 找y的老大
	if(x1 != x2){       // 如果不在同一个集合，就合并
		f[x1] = x2;
	}
}

int main() {
	cin >> n >> m;
	string ch;

	// ---------- 第一步：读入数据并准备离散化 ----------
	for(int i = 1; i <= m; i++) {
		cin >> a[i].x >> a[i].y >> ch;
		a[i].x--; // 把左端点 l 变成 l-1，这是为了转化为前缀和的点，方便计算 S_r - S_{l-1}

		// 判断Bob的回答是奇数还是偶数
		if(ch[0] == 'o') { // "odd" 奇数个1
			a[i].z = 1;
		} else {           // "even" 偶数个1
			a[i].z = 0;
		}

		// 收集所有出现过的前缀和下标（l-1 和 r），用于离散化
		b[++l] = a[i].x;
		b[++l] = a[i].y;
	}

	// ---------- 第二步：离散化 ----------
	sort(b + 1, b + l + 1); // 排序
	l = unique(b + 1, b + l + 1) - b - 1; // 去重，l 变成了实际不同前缀和下标的总数

	// ---------- 第三步：初始化扩展域并查集 ----------
	// 1 到 l 代表这些下标对应的前缀和是"偶数"
	// l+1 到 2*l 代表这些下标对应的前缀和是"奇数"
	for(int i = 1; i <= l * 2; i++) {
		f[i] = i;
	}

	// ---------- 第四步：处理每一组询问 ----------
	for(int i = 1; i <= m; i++) {
		// 将原先很大的坐标通过二分查找，映射到 1 到 l 的范围内
		a[i].x = lower_bound(b + 1, b + l + 1, a[i].x) - b;
		a[i].y = lower_bound(b + 1, b + l + 1, a[i].y) - b;

		if(a[i].z == 0) { // 情况1：回答 even（偶数个1），说明 S_{l-1} 和 S_r 奇偶性相同

			// 矛盾判定：如果 x 的"偶数域" 和 y 的"奇数域" 连通了，说明前面已推导出它们奇偶性不同
			if(zuxian(a[i].x) == zuxian(a[i].y + l)) {
				cout << i - 1; // 输出前一个满足条件的回答数
				return 0;
			}
			else {
				// 没有矛盾，合并两个平行世界的情况
				hebing(a[i].x, a[i].y);         // 假设 x是偶数，则 y也是偶数（偶数域连一起）
				hebing(a[i].x + l, a[i].y + l); // 假设 x是奇数，则 y也是奇数（奇数域连一起）
			}

		} else { // 情况2：回答 odd（奇数个1），说明 S_{l-1} 和 S_r 奇偶性不同

			// 矛盾判定：如果 x 的"偶数域" 和 y 的"偶数域" 连通了，说明前面已推导出它们奇偶性相同
			if(zuxian(a[i].x) == zuxian(a[i].y)) {
				cout << i - 1; // 矛盾，输出
				return 0;
			}
			else {
				// 没有矛盾，交叉合并平行世界
				hebing(a[i].x, a[i].y + l);     // 假设 x是偶数，则 y必须是奇数
				hebing(a[i].x + l, a[i].y);     // 假设 x是奇数，则 y必须是偶数
			}
		}
	}

	// 如果所有询问都没有矛盾，输出总询问数 m
	cout << m;
	return 0;
}//完结撒花
