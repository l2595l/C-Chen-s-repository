/*
================================================================================
                         重建树 · 带详细注释题解版
================================================================================

【题意】
  给定一棵包含 n 个节点、以 1 为根的有根树，树有 n-1 条边（编号 1 ~ n-1）。
  对于每一条边，把它切断后整棵树会分成两个连通块：
      S_i ：与根 1 相连的那一侧；
      T_i ：与根 1 不相连的那一侧。
  输入会给出每条边的这两个集合，但不保证哪个在前（即可能颠倒顺序），
  要求还原这棵树，并对除根节点外的每个节点 v（2 ~ n）输出两样东西：
      1) v 的父节点编号；
      2) 连接 v 与其父节点的那条边的编号。

【核心思想】
  关键观察：每一个 T_i 其实就是「某个节点的子树」。
  例如树 1-(2-(4,5))-3 中，
      边 (2,4) 切断后 T = {4}          —— 恰好是节点 4 的子树；
      边 (1,2) 切断后 T = {2,4,5}      —— 恰好是节点 2 的子树；
      边 (1,3) 切断后 T = {3}          —— 恰好是节点 3 的子树。

  为什么 T_i 一定是某棵子树？因为切掉一条边后，与根不相连的那一侧，
  就是该边"下方"端点所对应的子树。

  而"所有节点的子树"这一族集合有一个极好的性质——它们构成 laminar
  （层状）集合族：任意两棵子树，要么完全不相交，要么一棵包含另一棵。

  由这个性质可以推出两个决定性的结论：

  (1) 节点 v 的子树 = 所有「包含 v 的 T 集合」中【最小】的那个。
      理由：一个 T 集合包含 v，当且仅当它是 v 的某个祖先 w 的子树；
      而 subtree(v) ⊆ subtree(w)，所以 subtree(v) 一定是最小的那个。

  (2) 节点 v 的父亲 = 所有「包含 v 的 T 集合」中【第二小】的那个的"最高点"。
      理由：把这些包含 v 的集合按大小从小到大排：
          subtree(v)、subtree(父)、subtree(爷爷)、……
      第二小的正是 subtree(父)，而 subtree(父) 的"最高点"（根节点）就是父节点。
      注意 subtree(根 1) = 全集 V 不会出现在输入里（根没有父边），
      所以当 v 的父节点就是根 1 时，包含 v 的集合只有一个（subtree(v) 自己）。

【算法步骤】
  1. 读入每条边，用「与根相连的一侧一定包含节点 1」来区分 S 和 T，
     保留每条边的输入编号（这是要输出的边编号）。
  2. 把所有边按 |T| 从小到大排序（"剥洋葱"：先处理最底层的小子树）。
  3. 按升序给每个节点 v 建立 contain[v]：记录所有包含 v 的子树下标。
  4. contain[v][0] 就是 subtree(v)：
        - 从而该子树集合的"最高点" top_of = v；
        - 该节点的边编号 = 这个子树对应边的编号。
  5. 若 contain[v] 还有第二个元素，父节点 = top_of[contain[v][1]]；
     否则父节点 = 根 1。

【正确性】
  · 结论 (1)(2) 已在上文给出理由；两者共同保证每个节点的父节点、边编号
    都唯一且正确地被确定。
  · top_of 是良定义的：每个 T 集合恰好是某一个节点的子树，因此
    "contain[v][0] == 某集合" 的节点 v 恰好只有一个（就是该子树的根）。

【复杂度】
  时间 O(n^2)、空间 O(n^2)。
  输入本身把所有边的 S 和 T 都列出来，规模就已经是 O(n^2)，
  所以 n 不会太大，O(n^2) 完全够用。
================================================================================
*/

#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

// 一条边的信息
struct Edge {
    int id;              // 这条边在输入中的编号（1 ~ n-1），最终要作为答案输出
    vector<int> T;       // 切断这条边后，与根 1 不相连的那一侧集合（即某棵子树）
};

int main() {
    ios::sync_with_stdio(false);   // 关闭 C++ 与 C 的输入输出同步，加快 cin/cout
    cin.tie(nullptr);              // 解除 cin 与 cout 的绑定，进一步加快 IO

    int n;
    if (!(cin >> n)) return 0;     // 没读到 n 直接结束（防御性写法）

    vector<Edge> edges(n - 1);     // 一共有 n-1 条边

    // ---------------------------------------------------------------
    // 第 1 步：读入每条边，并确定它的 T（与根不相连的那一侧）
    // ---------------------------------------------------------------
    for (int i = 0; i < n - 1; i++) {
        edges[i].id = i + 1;       // 边编号按输入顺序 1,2,3,...

        // 读入第一个集合 a
        int m1; cin >> m1;
        vector<int> a(m1);
        for (int j = 0; j < m1; j++) cin >> a[j];

        // 读入第二个集合 b
        int m2; cin >> m2;
        vector<int> b(m2);
        for (int j = 0; j < m2; j++) cin >> b[j];

        // 关键：与根相连的一侧一定包含节点 1。
        // 因此哪个集合里有 1，哪个就是 S；另一个就是 T。
        // 这样即使输入把 S、T 的顺序颠倒，也能正确区分（不能靠集合大小判断！）。
        bool rootInA = false;
        for (int x : a) {
            if (x == 1) { rootInA = true; break; }
        }
        edges[i].T = rootInA ? b : a;
    }

    // ---------------------------------------------------------------
    // 第 2 步：按子树大小 |T| 从小到大排序（"剥洋葱"）
    //          先处理最底层的小子树，逐步向上
    // ---------------------------------------------------------------
    sort(edges.begin(), edges.end(), [](const Edge& x, const Edge& y) {
        return x.T.size() < y.T.size();
    });

    // ---------------------------------------------------------------
    // 第 3 步：建立 contain[v]
    //          contain[v] 记录"所有包含节点 v 的子树"的下标 s。
    //          由于 edges 已经按大小升序排好，而我们是按这个顺序往里 push，
    //          所以 contain[v] 天然就是【按大小升序】的。
    // ---------------------------------------------------------------
    vector<vector<int>> contain(n + 1);
    for (int s = 0; s < n - 1; s++) {
        for (int v : edges[s].T) {
            contain[v].push_back(s);
        }
    }

    // top_of[s] ：排序后第 s 个子树集合的"最高点"（即这棵子树的根节点）
    // ans_father[v] ：节点 v 的父节点编号
    // ans_edge[v]   ：连接节点 v 与其父节点的边编号
    vector<int> top_of(n - 1, 0);
    vector<int> ans_father(n + 1, 0);
    vector<int> ans_edge(n + 1, 0);

    // ---------------------------------------------------------------
    // 第 4 步：确定每个非根节点的子树
    //          节点 v 的子树 = 包含 v 的最小集合 = contain[v][0]
    // ---------------------------------------------------------------
    for (int v = 2; v <= n; v++) {
        int s0 = contain[v][0];        // subtree(v) 对应的排序下标
        top_of[s0] = v;                // 这个子树的最高点就是 v 自己
        ans_edge[v] = edges[s0].id;    // v 与父节点相连的边，正是 subtree(v) 那条边
    }

    // ---------------------------------------------------------------
    // 第 5 步：确定每个非根节点的父节点
    //          父节点 = 包含 v 的【第二小】集合的最高点；
    //          若只有一个集合包含 v，说明父节点是根 1。
    // ---------------------------------------------------------------
    for (int v = 2; v <= n; v++) {
        if ((int)contain[v].size() >= 2) {
            ans_father[v] = top_of[contain[v][1]];
        } else {
            ans_father[v] = 1;
        }
    }

    // ---------------------------------------------------------------
    // 第 6 步：输出（节点 2 ~ n，每个一行："父节点编号 边编号"）
    // ---------------------------------------------------------------
    for (int v = 2; v <= n; v++) {
        cout << ans_father[v] << " " << ans_edge[v] << "\n";
    }

    return 0;
}